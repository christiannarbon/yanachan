/**
 * Writes THIRD_PARTY_NOTICES.md: the third-party code inside the yanachan
 * binary, with each licence text. That is the npm packages the embedded
 * frontend bundle is built from, the Go modules linked into the server, and
 * the Go standard library and runtime.
 *
 * Fails, naming the package, when a package declares no licence or a Go
 * module ships a licence this script does not recognise: either is a question
 * for the owner, not something to paper over.
 *
 * Usage:  node scripts/third-party-notices.mjs
 */

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const frontend = join(root, 'frontend')
const backend = join(root, 'backend')
const licenceFile = /^(licen[cs]e|copying)(\..*)?$/i
const problems = []

const run = (cmd, args, cwd, env = {}) =>
  execFileSync(cmd, args, {
    cwd,
    encoding: 'utf8',
    maxBuffer: 64 << 20,
    env: { ...process.env, ...env },
  })

const licenceText = (dir) => {
  const file = existsSync(dir) ? readdirSync(dir).sort().find((f) => licenceFile.test(f)) : undefined
  return file ? readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd() : ''
}

const section = (title, licence, text) => {
  const fence = text.includes('```') ? '~~~~' : '```'
  return (
    `### ${title}\n\nLicense: ${licence}\n\n` +
    (text ? `${fence}text\n${text}\n${fence}\n` : '_The package ships no licence file._\n')
  )
}

// Go modules carry no licence field, so the text is classified. Only the
// licences seen so far are known; anything else stops the script.
const classify = (text) => {
  if (/Apache License\s+Version 2\.0/.test(text)) return 'Apache-2.0'
  if (/Permission is hereby granted, free of charge/.test(text)) return 'MIT'
  if (/Redistribution and use in source and binary forms/.test(text)) {
    return /Neither the name/.test(text) ? 'BSD-3-Clause' : 'BSD-2-Clause'
  }
  return ''
}

function npmSections() {
  const tree = JSON.parse(run('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], frontend))
  const packages = new Map()
  const walk = (node) => {
    for (const [name, dep] of Object.entries(node.dependencies ?? {})) {
      const key = `${name}@${dep.version}`
      if (!packages.has(key) || (!packages.get(key).dir && dep.path)) {
        packages.set(key, { name, version: dep.version, dir: dep.path })
      }
      walk(dep)
    }
  }
  walk(tree)

  const out = []
  for (const key of [...packages.keys()].sort()) {
    const p = packages.get(key)
    const dir = p.dir ?? join(frontend, 'node_modules', p.name)
    const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const licence = typeof meta.license === 'string' ? meta.license : meta.license?.type
    if (!licence) {
      problems.push(`npm ${key} declares no licence`)
      continue
    }
    out.push(section(`${p.name} ${p.version}`, licence, licenceText(dir)))
  }
  return out
}

function goSections() {
  // The image is built for Linux without cgo; list what that build links.
  const env = { GOOS: 'linux', CGO_ENABLED: '0', GOFLAGS: '-mod=readonly' }
  const lines = run(
    'go',
    ['list', '-deps', '-f', '{{if .Module}}{{if not .Module.Main}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}{{end}}', './cmd/server'],
    backend,
    env,
  )
  const modules = [...new Set(lines.split('\n').filter(Boolean))].sort()
  const out = []
  for (const line of modules) {
    const [path, version, dir] = line.split(' ')
    const text = licenceText(dir)
    const licence = classify(text)
    if (!licence) {
      problems.push(`go ${path}@${version} has no licence this script recognises`)
      continue
    }
    out.push(section(`${path} ${version}`, licence, text))
  }
  const goroot = run('go', ['env', 'GOROOT'], backend).trim()
  const stdlib = licenceText(goroot)
  out.push(section('Go standard library and runtime', classify(stdlib) || 'BSD-3-Clause', stdlib))
  return out
}

const npm = npmSections()
const go = goSections()

if (problems.length) {
  for (const p of problems) console.error(p)
  process.exit(1)
}

const doc = `# Third-party notices

Generated by \`make notices\`; do not edit by hand.

The yanachan binary, and so the image, contains the third-party code below,
each with the licence it is distributed under.

## Frontend bundle (npm)

These packages are compiled into the frontend bundle embedded in the binary.

${npm.join('\n')}
## Server (Go)

These modules are linked into the server.

${go.join('\n')}`

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), doc)
console.log(`THIRD_PARTY_NOTICES.md: ${npm.length} npm packages, ${go.length} Go entries`)
